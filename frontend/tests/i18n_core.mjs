import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const result = await build({ stdin:{contents:"export * from './src/i18n/index.ts'; export * from './src/utils/format.ts';", resolveDir:root, loader:'ts'}, bundle:true, write:false, platform:'node', format:'cjs' });
const module = { exports:{} };
new Function('module','exports','require',result.outputFiles[0].text)(module,module.exports,createRequire(import.meta.url));
const i18n = module.exports;
assert.equal(i18n.normalizeLocale('bad'), 'ko-KR');
assert.equal(i18n.normalizeLocale(null), 'ko-KR');
assert.equal(i18n.normalizeLocale('en'), 'en-US');
assert.equal(i18n.normalizeLocale('ja'), 'ja-JP');
assert.equal(i18n.normalizeLocale('ZH-tw'), 'zh-TW');
assert.equal(i18n.LOCALES.length, 8);
for (const locale of i18n.LOCALES) {
    i18n.setActiveLocale(locale);
    assert.equal(i18n.formatNumber(1234.5), new Intl.NumberFormat(locale).format(1234.5));
    assert.equal(i18n.formatDateTime('invalid'), '—');
    assert.equal(i18n.formatDateTime('2026-10-13T01:00:00Z'), new Intl.DateTimeFormat(locale).format(new Date('2026-10-13T01:00:00Z')));
    assert.ok(!i18n.translate('common.confirmTyping',{value:'<script>TEST</script>'}).includes('{value}'));
    for (const count of [0,1,2,5,21,22,25,1.5]) assert.ok(i18n.translatePlural('stats.count.day',count).includes(i18n.formatNumber(count)));
    assert.equal(i18n.translate('MP4 - MPEG-4'),'MP4 - MPEG-4');
    assert.equal(i18n.translate('C:\\recordings\\Live'),'C:\\recordings\\Live');
    assert.equal(i18n.translate('https://ci.me/@example/live'),'https://ci.me/@example/live');
    assert.equal(i18n.formatBytes(1234567890), `${i18n.formatNumber(1234567890 / 1024 ** 3, {minimumFractionDigits:2, maximumFractionDigits:2})} GB`);
    assert.equal(i18n.formatDuration(65, 'clock'), '00:01:05');
    assert.equal(i18n.formatDate('invalid'), '—');
    assert.equal(i18n.formatTime('invalid'), '—');
    assert.ok(!i18n.translatePlural('download.addedLinks', 1).includes('{count}'));
}
i18n.setActiveLocale('ru-RU');
assert.equal(i18n.translatePlural('stats.count.day',1),'1 день');
assert.equal(i18n.translatePlural('stats.count.day',2),'2 дня');
assert.equal(i18n.translatePlural('stats.count.day',5),'5 дней');
assert.equal(i18n.translatePlural('stats.count.day',21),'21 день');
i18n.setActiveLocale('de-DE');
const existing = i18n.translate('common.confirmTyping',{value:'Phrolova'});
i18n.setActiveLocale('ja-JP');
assert.equal(i18n.translate(existing), i18n.translate('common.confirmTyping',{value:'Phrolova'}));
assert.deepEqual(i18n.getMissingTranslations(),[]);
const warn = console.warn;
console.warn = () => {};
assert.equal(i18n.translate('common.missingFixture'), i18n.translate('common.textUnavailable'));
assert.deepEqual(i18n.getMissingTranslations(), ['ja-JP:common.missingFixture']);
console.warn = warn;
console.log('PASS: locale migration, invalid locale fallback, eight-locale numbers/dates, Russian plurals, interpolation, existing-message language switching, untouched paths/URLs/formats');
